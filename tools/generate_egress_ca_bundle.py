#!/usr/bin/env python3
"""Generate the upstream CA bundle ConfigMap for the central egress proxy.

The bundle is the pinned source bundle minus the denylist in egress_ca_policy.json. A root
from a blocked operator that the policy has not reviewed stops generation, so a new source
version cannot quietly reintroduce one.
"""

import argparse
import base64
import hashlib
import io
import json
import re
import ssl
import sys
import urllib.request
import zipfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
POLICY_PATH = ROOT / "tools/egress_ca_policy.json"
OUTPUT_PATH = ROOT / "infrastructure/central-egress/upstream-ca-bundle.yaml"
CONFIGMAP_NAME = "egress-proxy-upstream-ca"
NAMESPACE = "central-egress"
DATA_KEY = "ca-bundle.pem"
ANNOTATION_PREFIX = "egress-proxy.homelab.robinjoon.xyz"
PEM_BLOCK = re.compile(
    r'(?:# Label: "(?P<label>[^"\n]*)"\n(?:#[^\n]*\n|\s*\n)*)?'
    r"-----BEGIN CERTIFICATE-----\n(?P<body>[A-Za-z0-9+/=\n]+?)-----END CERTIFICATE-----"
)


class PolicyError(Exception):
    pass


def load_certificates(pem):
    certificates = []
    for match in PEM_BLOCK.finditer(pem):
        try:
            der = base64.b64decode(match["body"].replace("\n", ""), validate=True)
        except ValueError as error:
            raise PolicyError(f"Invalid certificate encoding: {error}") from error
        certificates.append({
            "label": match["label"] or "",
            "der": der,
            "sha256": hashlib.sha256(der).hexdigest(),
        })
    if len(certificates) != pem.count("-----BEGIN"):
        raise PolicyError("The source contains a block that is not a well-formed certificate")
    return certificates


def validate_bundle(pem, expected_count):
    """Load the bundle the way a TLS client would; every entry must be a real CA certificate."""
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    try:
        context.load_verify_locations(cadata=pem)
    except (ssl.SSLError, ValueError) as error:
        raise PolicyError(f"The bundle does not load as X.509: {error}") from error
    stats = context.cert_store_stats()
    if stats["x509"] != expected_count or stats["x509_ca"] != expected_count:
        raise PolicyError(
            f"Expected {expected_count} CA certificates, loaded {stats['x509_ca']} CA "
            f"out of {stats['x509']} certificates"
        )


def filter_certificates(certificates, policy):
    """Return (kept, removed), or raise when the result would break the policy."""
    blocked = policy["blockedRoots"]
    reviewed = policy["reviewedOperatorRoots"]
    markers = [marker.encode() for marker in policy["operatorMarkers"]]
    overlap = blocked.keys() & reviewed.keys()
    if overlap:
        raise PolicyError(f"Roots are both blocked and reviewed: {sorted(overlap)}")

    kept, removed, seen = [], [], set()
    for certificate in certificates:
        fingerprint = certificate["sha256"]
        if fingerprint in seen:
            continue
        seen.add(fingerprint)
        if fingerprint in blocked:
            removed.append(certificate)
            continue
        if fingerprint not in reviewed and any(m in certificate["der"] for m in markers):
            raise PolicyError(
                f"Unreviewed root from a blocked operator: {certificate['label']} ({fingerprint}). "
                "Add it to blockedRoots or reviewedOperatorRoots."
            )
        kept.append(certificate)
    if len(kept) < policy["minimumRoots"]:
        raise PolicyError(f"Only {len(kept)} roots remain; expected at least {policy['minimumRoots']}")
    return kept, removed


def render_pem(certificates):
    blocks = []
    for certificate in certificates:
        encoded = base64.b64encode(certificate["der"]).decode()
        lines = [encoded[i:i + 64] for i in range(0, len(encoded), 64)]
        blocks.append("\n".join([
            f'# Label: "{certificate["label"]}"',
            f"# SHA256: {certificate['sha256']}",
            "-----BEGIN CERTIFICATE-----",
            *lines,
            "-----END CERTIFICATE-----",
        ]))
    return "\n".join(blocks) + "\n"


def render_configmap(pem, certificates, source):
    indented = "".join(f"    {line}\n" for line in pem.splitlines())
    return (
        "# Generated by tools/generate_egress_ca_bundle.py. Do not edit by hand.\n"
        "apiVersion: v1\n"
        "kind: ConfigMap\n"
        "metadata:\n"
        f"  name: {CONFIGMAP_NAME}\n"
        f"  namespace: {NAMESPACE}\n"
        "  annotations:\n"
        f'    {ANNOTATION_PREFIX}/source: "{source["package"]}=={source["version"]}"\n'
        f'    {ANNOTATION_PREFIX}/source-sha256: "{source["sha256"]}"\n'
        f'    {ANNOTATION_PREFIX}/bundle-sha256: "{hashlib.sha256(pem.encode()).hexdigest()}"\n'
        f'    {ANNOTATION_PREFIX}/root-count: "{len(certificates)}"\n'
        "data:\n"
        f"  {DATA_KEY}: |\n"
        f"{indented}"
    )


def fetch_source(source, wheel_path=None):
    if wheel_path:
        wheel = Path(wheel_path).read_bytes()
    else:
        with urllib.request.urlopen(source["url"], timeout=60) as response:
            wheel = response.read()
    digest = hashlib.sha256(wheel).hexdigest()
    if digest != source["sha256"]:
        raise PolicyError(f"Source hash mismatch: expected {source['sha256']}, got {digest}")
    with zipfile.ZipFile(io.BytesIO(wheel)) as archive:
        return archive.read(source["member"]).decode()


def existing_fingerprints(path):
    if not path.exists():
        return set()
    return set(re.findall(r"# SHA256: ([0-9a-f]{64})", path.read_text()))


def generate(policy, source_pem):
    kept, removed = filter_certificates(load_certificates(source_pem), policy)
    pem = render_pem(kept)
    validate_bundle(pem, len(kept))
    return render_configmap(pem, kept, policy["source"]), kept, removed


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", type=Path, default=POLICY_PATH)
    parser.add_argument("--output", type=Path, default=OUTPUT_PATH)
    parser.add_argument("--source-wheel", help="use this local wheel instead of downloading it")
    parser.add_argument("--check", action="store_true", help="fail if the output is out of date")
    args = parser.parse_args(argv)

    try:
        policy = json.loads(args.policy.read_text())
        rendered, kept, removed = generate(policy, fetch_source(policy["source"], args.source_wheel))
    except (PolicyError, OSError, KeyError, ValueError, zipfile.BadZipFile) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    previous = existing_fingerprints(args.output)
    current = {certificate["sha256"] for certificate in kept}
    print(json.dumps({
        "source": f'{policy["source"]["package"]}=={policy["source"]["version"]}',
        "roots": len(kept),
        "filtered": sorted(certificate["label"] for certificate in removed),
        "added": sorted(current - previous),
        "removed": sorted(previous - current),
    }, indent=2))

    if args.check:
        if not args.output.exists() or args.output.read_text() != rendered:
            print(f"error: {args.output} is out of date", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main())
